_cache = {}


def _render(name, px, color, stroke=None):
    s = px * SS / GRID
    img = Image.new("RGBA", (px * SS, px * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    col = hex_rgb(color) + (255,)
    w = max(1, int(round((stroke or STROKE) * s)))

    def P(x, y):
        return (x * s, y * s)

    def cap(x, y):
        r = w / 2
        d.ellipse((x * s - r, y * s - r, x * s + r, y * s + r), fill=col)

    for pr in ICONS[name]:
        k = pr[0]
        if k == "l":
            d.line((P(pr[1], pr[2]), P(pr[3], pr[4])), fill=col, width=w)
            cap(pr[1], pr[2])
            cap(pr[3], pr[4])
        elif k == "p":
            pts = [P(x, y) for x, y in pr[1]]
            if pr[2]:
                pts = pts + [pts[0]]
            d.line(pts, fill=col, width=w, joint="curve")
            for x, y in pr[1]:
                cap(x, y)
        elif k == "c":
            cx, cy, r = pr[1:]
            d.ellipse((P(cx - r, cy - r), P(cx + r, cy + r)), outline=col, width=w)
        elif k == "d":
            cx, cy, r = pr[1:]
            d.ellipse((P(cx - r, cy - r), P(cx + r, cy + r)), fill=col)
        elif k == "r":
            x1, y1, x2, y2, rad = pr[1:]
            d.rounded_rectangle((P(x1, y1), P(x2, y2)), radius=rad * s, outline=col, width=w)
        elif k == "R":
            x1, y1, x2, y2, rad = pr[1:]
            d.rounded_rectangle((P(x1, y1), P(x2, y2)), radius=rad * s, fill=col)
        elif k == "a":
            cx, cy, r, a0, a1 = pr[1:]
            d.arc((P(cx - r, cy - r), P(cx + r, cy + r)), a0, a1, fill=col, width=w)
    return img.resize((px, px), Image.LANCZOS)


def pil_icon(name, px, color):
    return _render(name, px, color)


def icon_tight(name, px, color, stroke=None):
    """PhotoImage иконки, обрезанной по самому рисунку (без пустых полей сетки 24). Нужна, чтобы
    несимметричный значок (стрелка курсора: рисунок в левой верхней части сетки) стоял по центру
    строки ВИДИМО, а не по центру пустого квадрата. Кэшируется как icon()."""
    key = ("tight", name, px, color, stroke)
    if key not in _cache:
        im = _render(name, px, color, stroke)
        box = im.getbbox()
        _cache[key] = ImageTk.PhotoImage(im.crop(box) if box else im)
    return _cache[key]


def icon(name, px, color, stroke=None):
    """PhotoImage иконки (с прозрачностью). stroke — толщина штриха на сетке 24 (по умолчанию
    ICON.stroke). Кэшируется по (имя, размер, цвет, толщина)."""
    key = (name, px, color, stroke)
    if key not in _cache:
        _cache[key] = ImageTk.PhotoImage(_render(name, px, color, stroke))
    return _cache[key]
